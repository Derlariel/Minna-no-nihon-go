const digitsJP = ['', 'いち', 'に', 'さん', 'よん', 'ご', 'ろく', 'なな', 'はち', 'きゅう'];
function readNumber(n) {
  if (n === 0) return 'れい';
  if (n < 10) return digitsJP[n];
  const [unit, name, variants] = n >= 10000 ? [10000, 'まん', {}]
    : n >= 1000 ? [1000, 'せん', { 3: 'さんぜん', 8: 'はっせん' }]
    : n >= 100 ? [100, 'ひゃく', { 3: 'さんびゃく', 6: 'ろっぴゃく', 8: 'はっぴゃく' }]
    : [10, 'じゅう', {}];
  const count = Math.floor(n / unit);
  const head = variants[count] || ((count === 1 && unit !== 10000 ? '' : readNumber(count)) + name);
  return head + (n % unit ? readNumber(n % unit) : '');
}

function minuteReading(n) {
  const units = { 1: 'いっぷん', 3: 'さんぷん', 4: 'よんぷん', 6: 'ろっぷん', 8: 'はっぷん' };
  if (n % 10 === 0) return readNumber(n).replace(/じゅう$/, 'じゅっぷん');
  const ones = n % 10;
  return (n > 10 ? readNumber(n - ones) : '') + (units[ones] || digitsJP[ones] + 'ふん');
}

function dateReading(n) {
  const exceptions = ['','ついたち','ふつか','みっか','よっか','いつか','むいか','なのか','ようか','ここのか','とおか'];
  return exceptions[n] || ({14: 'じゅうよっか', 20: 'はつか', 24: 'にじゅうよっか', 17: 'じゅうしちにち', 19: 'じゅうくにち', 27: 'にじゅうしちにち', 29: 'にじゅうくにち'}[n] || readNumber(n) + 'にち');
}

